// Makes the app's sample job from a saved job file and its photo folder:
//   npm run sample:make -- "<job.axb>" "<photo folder>"
// Writes src/ui/sampleJobData.ts (the job, with the client, unit, inspector, notes and folder paths taken out and only
// the settings that differ from the defaults) and public/sample-photos/<name>.jpg (each linked photo as a JPEG, quality
// 85, so the app can keep them for offline use). The sample in use is REF1's V-100 (user, 2026-10-26).
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, extname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { inflateSync } from 'node:zlib'
import jpeg from 'jpeg-js'
import { createEmptyProject, openProject } from '../src/data/projectFile.ts'
import { resolveImageFile } from '../src/data/imageMatch.ts'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')

/** RGBA pixels of an 8-bit, non-interlaced PNG (gray, RGB, gray + alpha or RGBA). */
function decodePng(buf: Buffer): { width: number; height: number; data: Buffer } {
  let pos = 8
  let width = 0
  let height = 0
  let type = 0
  const idat: Buffer[] = []
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos)
    const kind = buf.toString('ascii', pos + 4, pos + 8)
    const body = buf.subarray(pos + 8, pos + 8 + len)
    if (kind === 'IHDR') {
      width = body.readUInt32BE(0)
      height = body.readUInt32BE(4)
      type = body[9]
      if (body[8] !== 8 || body[12] !== 0) throw new Error('Only 8-bit, non-interlaced PNGs are read.')
    } else if (kind === 'IDAT') idat.push(body)
    pos += 12 + len
  }
  const bpp = { 0: 1, 2: 3, 4: 2, 6: 4 }[type]
  if (!bpp) throw new Error(`PNG color type ${type} is not read.`)
  const raw = inflateSync(Buffer.concat(idat))
  const stride = width * bpp
  const px = Buffer.alloc(stride * height)
  for (let y = 0; y < height; y++) {
    const f = raw[y * (stride + 1)]
    for (let x = 0; x < stride; x++) {
      const v = raw[y * (stride + 1) + 1 + x]
      const a = x >= bpp ? px[y * stride + x - bpp] : 0
      const b = y > 0 ? px[(y - 1) * stride + x] : 0
      const c = x >= bpp && y > 0 ? px[(y - 1) * stride + x - bpp] : 0
      const p = a + b - c
      const pred = f === 0 ? 0 : f === 1 ? a : f === 2 ? b : f === 3 ? (a + b) >> 1 : Math.abs(p - a) <= Math.abs(p - b) && Math.abs(p - a) <= Math.abs(p - c) ? a : Math.abs(p - b) <= Math.abs(p - c) ? b : c
      px[y * stride + x] = (v + pred) & 255
    }
  }
  const data = Buffer.alloc(width * height * 4)
  for (let i = 0; i < width * height; i++) {
    const s = px.subarray(i * bpp, i * bpp + bpp)
    const rgb = bpp >= 3 ? [s[0], s[1], s[2]] : [s[0], s[0], s[0]]
    data.set([...rgb, 255], i * 4)
  }
  return { width, height, data }
}

function main() {
  const [jobFile, photoDir] = process.argv.slice(2)
  if (!jobFile || !photoDir) throw new Error('Usage: npm run sample:make -- "<job.axb>" "<photo folder>"')
  const opened = openProject(readFileSync(jobFile, 'utf8'))
  if (!opened.ok) throw new Error(opened.errors.join('\n'))
  const p = opened.project
  const blank = createEmptyProject()

  // Nothing that names the client, the site or a person, and no folder on this computer.
  const project = { ...p.project, client: 'Sample Client', unit: 'Sample Unit', inspector: 'A. Inspector' }
  for (const k of ['drawingNotes', 'inspectionNotes', 'reportNumber', 'workOrder', 'procedure'] as const) project[k] = ''
  const settings: Record<string, unknown> = {}
  for (const [k, v] of Object.entries(p.settings)) {
    if (k === 'originalImageFolder' || k === 'processedImageFolder') continue
    if (JSON.stringify(v) !== JSON.stringify((blank.settings as Record<string, unknown>)[k])) settings[k] = v
  }

  // Photos: each linked one as a JPEG in public/sample-photos, linked by that name.
  const outDir = join(APP, 'public', 'sample-photos')
  rmSync(outDir, { recursive: true, force: true })
  mkdirSync(outDir, { recursive: true })
  const names = readdirSync(photoDir)
  const scanImages = p.scanImages.map((l) => {
    const file = resolveImageFile(l.imageFile, names)
    if (!file || extname(file).toLowerCase() !== '.png') throw new Error(`No PNG photo for ${l.scanId} (${l.imageFile}).`)
    const name = `${basename(file, extname(file))}.jpg`
    const img = decodePng(readFileSync(join(photoDir, file)))
    writeFileSync(join(outDir, name), jpeg.encode(img, 85).data)
    console.log(`Wrote public/sample-photos/${name} (${img.width} x ${img.height})`)
    return { scanId: l.scanId, imageFile: name, processedImage: '', include: l.include }
  })

  const { jobId: _jobId, ...rest } = p
  void _jobId
  const data = { ...rest, project, settings, scanImages }
  writeFileSync(join(APP, 'src', 'ui', 'sampleJobData.ts'), [
    `// Generated by scripts/make-sample.ts from ${basename(jobFile)} (client, unit, inspector, notes and folders taken out); do not edit.`,
    '// Its photos are public/sample-photos/. To change the sample, save a job and run npm run sample:make again.',
    '',
    "import type { ProjectInput } from '../data/schema.ts'",
    '',
    `export const SAMPLE_DATA = ${JSON.stringify(data, null, 2)} as const satisfies ProjectInput`,
    '',
  ].join('\n'))
  console.log('Wrote src/ui/sampleJobData.ts')
}

main()
