// Writes src/engine/fontMetrics.generated.ts from the font the app bundles for the PDF, the report images and
// the Sheets view (Arimo Regular): the advance width of every character from 32 to 255 and the cap height,
// so the sheet model measures text exactly as the PDF draws it.   npm run gen:font-metrics
// (test/engine/sheetModel.test.ts fails when the table is out of date.)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import fontkit from '@pdf-lib/fontkit'

export const FONT_FILE = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'fonts', 'Arimo-Regular.ttf')

export function renderFontMetrics(): string {
  const font = fontkit.create(readFileSync(FONT_FILE))
  const widths: number[] = []
  for (let c = 32; c <= 255; c++) widths.push(font.glyphForCodePoint(c).advanceWidth)
  return [
    '// Generated by scripts/gen-font-metrics.ts from Arimo Regular (the font bundled for the PDF); do not edit.',
    '// Advance widths for characters 32 to 255 in font units, and the font\'s vertical metrics.',
    '',
    `export const FONT_UNITS_PER_EM = ${font.unitsPerEm}`,
    `export const FONT_CAP_HEIGHT = ${font.capHeight}`,
    `export const FONT_ASCENT = ${font.ascent}`,
    `export const FONT_DESCENT = ${font.descent}`,
    `export const FONT_WIDTHS: readonly number[] = [${widths.join(', ')}]`,
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'engine', 'fontMetrics.generated.ts')
  writeFileSync(out, renderFontMetrics())
  console.log(`Wrote ${out}`)
}
