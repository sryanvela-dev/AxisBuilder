// Writes the generated font metrics from the fonts the app bundles, so text is measured exactly as the PDF draws it:
// - src/engine/fontMetrics.generated.ts: Arimo Regular (the drawing PDF, the report images and the Sheets view), the
//   advance width of every character from 32 to 255 and the cap height
// - src/report/fontMetrics.generated.ts: the report fonts (Montserrat 600 / 700, Roboto 400 / 500 / 700), the same
//   widths plus the typographic marks the report uses (dashes, curly quotes, bullet, ...)
//   npm run gen:font-metrics
// (test/export/pdf.test.ts and test/report/fonts.test.ts fail when a table is out of date.)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import fontkit from '@pdf-lib/fontkit'

const FONTS_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'fonts')
export const FONT_FILE = join(FONTS_DIR, 'Arimo-Regular.ttf')

/** The report fonts: id -> file in src/assets/fonts (the ids are report/fonts.ts ReportFontId). */
export const REPORT_FONT_FILES = {
  'montserrat-600': 'Montserrat-SemiBold.ttf',
  'montserrat-700': 'Montserrat-Bold.ttf',
  'roboto-400': 'Roboto-Regular.ttf',
  'roboto-500': 'Roboto-Medium.ttf',
  'roboto-700': 'Roboto-Bold.ttf',
} as const

/** Characters above 255 the report measures (anything else counts as 0.6 em). */
export const EXTRA_CODE_POINTS = [0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x2264, 0x2265, 0x21ba]

export function renderFontMetrics(): string {
  const font = fontkit.create(readFileSync(FONT_FILE))
  const widths: number[] = []
  for (let c = 32; c <= 255; c++) widths.push(font.glyphForCodePoint(c).advanceWidth)
  return [
    '// Generated by scripts/gen-font-metrics.ts from Arimo Regular (the font bundled for the PDF); do not edit.',
    '// Advance widths for characters 32 to 255 in font units, and the font\'s vertical metrics.',
    '',
    `export const FONT_UNITS_PER_EM = ${font.unitsPerEm}`,
    `export const FONT_CAP_HEIGHT = ${font.capHeight}`,
    `export const FONT_ASCENT = ${font.ascent}`,
    `export const FONT_DESCENT = ${font.descent}`,
    `export const FONT_WIDTHS: readonly number[] = [${widths.join(', ')}]`,
    '',
  ].join('\n')
}

export function renderReportFontMetrics(): string {
  const lines = [
    '// Generated by scripts/gen-font-metrics.ts from the report fonts in src/assets/fonts; do not edit.',
    '// Per font: units per em, cap height, ascent, descent, advance widths for characters 32 to 255 and a few more.',
    '',
    'export interface FontMetricsTable {',
    '  unitsPerEm: number',
    '  capHeight: number',
    '  ascent: number',
    '  descent: number',
    '  widths: readonly number[]',
    '  extra: Readonly<Record<number, number>>',
    '}',
    '',
    'export const REPORT_FONT_METRICS = {',
  ]
  for (const [id, file] of Object.entries(REPORT_FONT_FILES)) {
    const font = fontkit.create(readFileSync(join(FONTS_DIR, file)))
    const widths: number[] = []
    for (let c = 32; c <= 255; c++) widths.push(font.glyphForCodePoint(c).advanceWidth)
    const extra = EXTRA_CODE_POINTS.filter((c) => font.glyphForCodePoint(c).id !== 0).map((c) => `${c}: ${font.glyphForCodePoint(c).advanceWidth}`)
    lines.push(
      `  '${id}': {`,
      `    unitsPerEm: ${font.unitsPerEm}, capHeight: ${font.capHeight}, ascent: ${font.ascent}, descent: ${font.descent},`,
      `    widths: [${widths.join(', ')}],`,
      `    extra: { ${extra.join(', ')} },`,
      '  },',
    )
  }
  lines.push('} as const satisfies Record<string, FontMetricsTable>', '')
  return lines.join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src')
  writeFileSync(join(root, 'engine', 'fontMetrics.generated.ts'), renderFontMetrics())
  writeFileSync(join(root, 'report', 'fontMetrics.generated.ts'), renderReportFontMetrics())
  console.log('Wrote src/engine/fontMetrics.generated.ts and src/report/fontMetrics.generated.ts')
}
