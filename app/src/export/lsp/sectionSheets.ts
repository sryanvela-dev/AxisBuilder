// ABSECTIONSHEETS (Phase 3f-2, app output only, written only while section sheets are on): builds the
// section sheets the app planned (engine/sections.ts), from exactly those ranges, on copies of the
// letter-size template Sheet, as v5.0's SECTIONPAGES does (same viewport layout, rulers, references and
// information panel). What is left in CAD: be on the template Sheet tab, and pick its viewport only when
// the sheet has more than one. SECTIONPAGES stays in the .lsp as the backup.

import type { SectionPlan } from '../../engine/sections.ts'
import { LispNum } from './vbaFormat.ts'

const nl = '\\n'

export function writeSectionSheets(w: (line: string) => void, plan: SectionPlan): void {
  const n = (v: number | null) => (v === null ? 'nil' : String(v))
  const tf = (b: boolean) => (b ? 'T' : 'nil')
  w(';;; ---- Section sheets planned in the app: ABSECTIONSHEETS builds exactly these (SECTIONPAGES stays as the backup) ----')
  w(';; Each section: (number start end viewStart viewEnd previous next); previous / next = the section a match line points to.')
  w(`(setq SL_APP_SECTIONS (list ${plan.sections.map((s) => `(list ${s.n} ${LispNum(s.start)} ${LispNum(s.end)} ${LispNum(s.viewStart)} ${LispNum(s.viewEnd)} ${n(s.prev)} ${n(s.next)})`).join(' ')}))`)
  w(`(setq SL_APP_SECTION_COUNT ${plan.sections.length})`)
  w(`(setq SL_APP_SECTION_OVERVIEW ${tf(plan.overview)})`)
  w(`(setq SL_APP_SECTION_MATCH ${tf(plan.matchLines)})`)
  w(`(setq SL_APP_SECTION_NOFN ${tf(plan.numberInTitle)})`)
  w(`(setq SL_APP_SECTION_RULER_SCALE ${LispNum(plan.rulerTextScale)})`)
  w('')
  w(';; The template Sheet\'s viewport when it has exactly one (DXF 69 > 1 skips the sheet\'s own paper viewport); else nil.')
  w('(defun SL_AppTemplateViewport ( / ss i ent ed found count)')
  w('  (setq ss (ssget "_X" (list (cons 0 "VIEWPORT") (cons 410 (getvar "CTAB")))) i 0 count 0 found nil)')
  w('  (if ss')
  w('    (repeat (sslength ss)')
  w('      (setq ent (ssname ss i) i (1+ i) ed (entget ent))')
  w('      (if (and (assoc 69 ed) (> (cdr (assoc 69 ed)) 1)) (setq found ent count (1+ count)))')
  w('    )')
  w('  )')
  w('  (if (= count 1) found nil)')
  w(')')
  w('')
  w(';; Paper X (from the viewport\'s left) of y along the shell on a sheet showing vs..ve; CCW runs right to left.')
  w('(defun SL_AppPaperX (y vs ve sc)')
  w('  (if (= SL_ORIENTATION "Horizontal CCW") (* (- ve y) sc) (* (- y vs) sc))')
  w(')')
  w('')
  w('(defun c:ABSECTIONSHEETS ( / *error* oldOsmode oldCmdecho pick templateVp ed ctr areaW areaH left bottom templateName')
  w('                              leftMargin bottomMargin usableW usableH paperUnit pages page num startPos endPos vs ve prev next')
  w('                              viewLen scale vpW vpH vpLeft vpBottom sheetName firstSheet ll ur vp win1 win2 infoX infoTop')
  w('                              title x0 x1 s count)')
  w('  (setq oldOsmode (getvar "OSMODE") oldCmdecho (getvar "CMDECHO"))')
  w('  (defun *error* (msg)')
  w('    (setvar "OSMODE" oldOsmode)')
  w('    (setvar "CMDECHO" oldCmdecho)')
  w(`    (if (and msg (/= msg "Function cancelled") (/= msg "quit / exit abort")) (princ (strcat "${nl}ABSECTIONSHEETS error: " msg)))`)
  w('    (princ)')
  w('  )')
  w('  (cond')
  w('    ((or (null SL_VESSEL_XLEN) (null SL_VESSEL_YLEN))')
  w('      (SL_SectionPagesStop "Generate the drawing first (option 1 / AXISDRAWING in the AXISBUILDER menu), then run ABSECTIONSHEETS again."))')
  w('    ((/= (getvar "TILEMODE") 0)')
  w('      (SL_SectionPagesStop "Switch to the letter-size template Sheet tab (paper space), then run ABSECTIONSHEETS again."))')
  w('    ((= SL_ORIENTATION "Vertical")')
  w('      (SL_SectionPagesStop "Section sheets are not available for Vertical orientation yet."))')
  w('    ((null SL_APP_SECTIONS)')
  w('      (SL_SectionPagesStop "The job has no section sheets planned (Drawing step, Section sheets)."))')
  w('    (T')
  w('      (setq templateVp (SL_AppTemplateViewport))')
  w('      (if (null templateVp)')
  w('        (progn')
  w(`          (setq pick (entsel "${nl}Select the template viewport that defines the printable report area: "))`)
  w('          (if pick (setq templateVp (car pick)))')
  w('        )')
  w('      )')
  w('      (if (and templateVp (= (cdr (assoc 0 (entget templateVp))) "VIEWPORT"))')
  w('        (progn')
  w('          (setq SL_REPORT_RULER_TEXT_SCALE SL_APP_SECTION_RULER_SCALE)')
  w('          (setq ed (entget templateVp) ctr (cdr (assoc 10 ed)) areaW (cdr (assoc 40 ed)) areaH (cdr (assoc 41 ed)))')
  w('          (setq left (- (car ctr) (/ areaW 2.0)) bottom (- (cadr ctr) (/ areaH 2.0)))')
  w('          (setq templateName (getvar "CTAB"))')
  w('          ;; As SECTIONPAGES: the section gets 68% of the sheet, the right information panel the rest.')
  w('          (setq leftMargin (* areaW 0.13) bottomMargin (* areaH 0.08) paperUnit (/ areaH 7.5))')
  w('          (setq usableW (* areaW 0.68) usableH (- areaH bottomMargin))')
  w('          (setvar "OSMODE" 0)')
  w('          (setvar "CMDECHO" 0)')
  w('          (SL_Layer "REPORT_X_RULER" 1)')
  w('          (SL_Layer "REPORT_Y_RULER" 5)')
  w('          (SL_Layer "REPORT_X_REFERENCE" 1)')
  w('          (SL_Layer "REPORT_TITLE" 7)')
  w('          (SL_Layer "REPORT_LEGEND" 7)')
  w('          (SL_Layer "REPORT_LEGEND_AUT" 5)')
  w('          (SL_Layer "REPORT_LEGEND_MUT" 3)')
  w('          (SL_Layer "REPORT_LEGEND_AUT_BOX" 5)')
  w('          (SL_Layer "REPORT_LEGEND_MUT_BOX" 3)')
  w('          (SL_SetLayerTransparency "REPORT_LEGEND_AUT,REPORT_LEGEND_MUT")')
  w('          (SL_Layer "REPORT_VIEWPORT" 7)')
  w('          (SL_SetLayerPlottable "REPORT_VIEWPORT" T)')
  w('          (SL_Layer "REPORT_MATCH_LINE" 1)')
  w('          (SL_Layer "REPORT_SECTION_BOX" 3)')
  w('          ;; The overview (number 0, the whole shell) first when asked, then the sections.')
  w('          (setq pages (if SL_APP_SECTION_OVERVIEW (cons (list 0 0.0 SL_VESSEL_YLEN 0.0 SL_VESSEL_YLEN nil nil) SL_APP_SECTIONS) SL_APP_SECTIONS))')
  w('          (setq firstSheet nil count 0)')
  w('          (foreach page pages')
  w('            (setq num (nth 0 page) startPos (nth 1 page) endPos (nth 2 page) vs (nth 3 page) ve (nth 4 page) prev (nth 5 page) next (nth 6 page))')
  w('            (setq viewLen (- ve vs))')
  w('            (setq scale (min (/ usableW viewLen) (/ usableH SL_VESSEL_XLEN)))')
  w('            (setq vpW (* viewLen scale) vpH (* SL_VESSEL_XLEN scale))')
  w('            (setq sheetName (strcat "AB-SEC-" (if (< num 10) "0" "") (itoa num) (if (= num 0) "_OVERVIEW" (strcat "_" (rtos startPos 2 0) "-" (rtos endPos 2 0)))))')
  w('            (SL_CopySheet templateName sheetName)')
  w('            (SL_ActivateSheet sheetName)')
  w('            (if (null firstSheet) (setq firstSheet sheetName))')
  w('            (SL_ClearSectionSheet sheetName)')
  w('            (setq vpLeft (+ left leftMargin (/ (- usableW vpW) 2.0)))')
  w('            (setq vpBottom (+ bottom bottomMargin (/ (- usableH vpH) 2.0)))')
  w('            (setq ll (list vpLeft vpBottom) ur (list (+ vpLeft vpW) (+ vpBottom vpH)))')
  w('            (SL_SetLayer "REPORT_VIEWPORT")')
  w('            (SL_CreateViewport ll ur)')
  w('            (setq vp (entlast))')
  w('            (if (= SL_ORIENTATION "Horizontal CCW")')
  w('              (progn (setq win1 (list (- ve) 0.0)) (setq win2 (list (- vs) SL_VESSEL_XLEN)))')
  w('              (progn (setq win1 (list vs (- SL_VESSEL_XLEN))) (setq win2 (list ve 0.0)))')
  w('            )')
  w('            (SL_ActivateViewport vp)')
  w('            (command "ZOOM" "W" win1 win2)')
  w('            (SL_ReturnPaperSpace)')
  w('            (SL_LockViewport vp)')
  w('            (SL_PaperSectionRulers vpLeft vpBottom vpW vpH vs viewLen)')
  w('            (SL_PaperSectionReferences vpLeft vpBottom vpW vpH)')
  w('            (setq infoX (+ left (* areaW 0.865)) infoTop (+ vpBottom (* 2.55 paperUnit)))')
  w('            (SL_PaperSectionInfo infoX infoTop paperUnit)')
  w('            (setq title (cond ((= num 0) "OVERVIEW") (SL_APP_SECTION_NOFN (strcat "SECTION " (itoa num) " OF " (itoa SL_APP_SECTION_COUNT))) (T (strcat "SECTION " (itoa num)))))')
  w('            (SL_PaperText (+ vpLeft (/ vpW 2.0)) (+ vpBottom vpH (* 0.22 paperUnit)) (* 0.18 paperUnit) 0 title "REPORT_TITLE")')
  w('            ;; Overview: a numbered box for each section.')
  w('            (if (= num 0)')
  w('              (foreach s SL_APP_SECTIONS')
  w('                (setq x0 (+ vpLeft (SL_AppPaperX (nth 1 s) vs ve scale)) x1 (+ vpLeft (SL_AppPaperX (nth 2 s) vs ve scale)))')
  w('                (SL_PaperRect (min x0 x1) vpBottom (abs (- x1 x0)) vpH "REPORT_SECTION_BOX")')
  w('                (SL_PaperText (/ (+ x0 x1) 2.0) (- (+ vpBottom vpH) (* 0.2 paperUnit)) (* 0.14 paperUnit) 0 (itoa (nth 0 s)) "REPORT_SECTION_BOX")')
  w('              )')
  w('            )')
  w('            ;; Match lines where the next or previous section carries on.')
  w('            (if (and (> num 0) SL_APP_SECTION_MATCH)')
  w('              (foreach s (list (list startPos prev) (list endPos next))')
  w('                (if (cadr s)')
  w('                  (progn')
  w('                    (setq x0 (+ vpLeft (SL_AppPaperX (car s) vs ve scale)))')
  w('                    (SL_PaperLine x0 vpBottom x0 (+ vpBottom vpH) "REPORT_MATCH_LINE")')
  w('                    (SL_PaperText (- x0 (* 0.08 paperUnit)) (+ vpBottom (/ vpH 2.0)) (* 0.1 paperUnit) 90 (strcat "MATCH LINE - SEE SECTION " (itoa (cadr s))) "REPORT_MATCH_LINE")')
  w('                  )')
  w('                )')
  w('              )')
  w('            )')
  w('            (setq count (1+ count))')
  w('          )')
  w('          (if firstSheet (SL_ActivateSheet firstSheet))')
  w('          (setvar "CMDECHO" oldCmdecho)')
  w('          (command "_.REGEN")')
  w(`          (princ (strcat "${nl}Created " (itoa count) " section sheet tab(s) from the plan made in AxisBuilder."))`)
  w('        )')
  w(`        (princ "${nl}ABSECTIONSHEETS cancelled: no sheet viewport chosen.")`)
  w('      )')
  w('    )')
  w('  )')
  w('  (setvar "OSMODE" oldOsmode)')
  w('  (setvar "CMDECHO" oldCmdecho)')
  w('  (princ)')
  w(')')
  w(`(princ "${nl}Section sheets: after drawing, switch to the letter-size Sheet tab and type ABSECTIONSHEETS.")`)
  w('')
}
